"""Phase 13 — Report and Cost/Resource Generator.

Two public classes
------------------
CostReportGenerator
    Accepts the stored experiment dict (from ExperimentManager.get_experiment())
    and produces a cost_report dict whose shape matches contracts/cost_report.json.

ReportGenerator
    Accepts the same experiment dict (plus an optional cost report and optional
    explanation dicts) and produces a full 16-section HTML experiment report.
    Also persists the report to artifacts/reports/{experiment_id}_report.html.

Design rules
------------
- Never retrain or call model.fit().
- Never claim medical causality or diagnoses.
- Never interpret an uncalibrated score as a clinical probability.
- Never claim quantum advantage is proven — only "observed on this dataset".
- financial_cost_local.estimate is ALWAYS 0 for local runs.
- The HTML report MUST contain the heading "RESEARCH / BENCHMARKING SYSTEM".

Compatibility
-------------
Works from the serialised experiment dict stored by ExperimentManager.  The
generator never imports live model objects; it only reads dicts. This means
it is safe to call from the FastAPI layer without PennyLane in scope.
"""

