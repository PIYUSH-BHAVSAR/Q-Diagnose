class CostReportGenerator:
    """Generates the cost_report dict matching contracts/cost_report.json.

    Accepts the experiment dict returned by ExperimentManager.get_experiment()
    — i.e., ``experiment["results"]`` already contains serialised model dicts.

    Usage
    -----
    generator = CostReportGenerator()
    cost_report = generator.generate(experiment)
    """

    def generate(self, experiment: dict) -> dict:
        """Build cost report from a stored experiment dict.

        Parameters
        ----------
        experiment : dict
            Full experiment dict as returned by
            ``ExperimentManager.get_experiment()``.

        Returns
        -------
        dict matching contracts/cost_report.json
        """
        experiment_id = experiment.get("id", "UNKNOWN")
        dataset_id    = experiment.get("dataset_id", "UNKNOWN")
        results       = experiment.get("results", {})
        models        = results.get("models", {})
        comparison    = results.get("comparison", {})
        resource_usage = results.get("resource_usage", {})
        preprocessing  = results.get("preprocessing", {})

        logger.info(f"CostReportGenerator: generating cost report for {experiment_id}")

        # ── Find best quantum model (by ROC-AUC) ─────────────────────────
        quantum_models = {
            k: v for k, v in models.items()
            if v.get("model_type") == "QUANTUM" or k.lower() in ("vqc", "quantumsvm")
        }
        best_q_name = "N/A"
        best_q_data = {}
        best_q_auc = -1.0
        for qname, qdata in quantum_models.items():
            qm = (qdata or {}).get("metrics", {})
            qauc = _safe_float(qm.get("roc_auc"))
            if qauc > best_q_auc:
                best_q_auc = qauc
                best_q_name = qname
                best_q_data = qdata

        best_q_metrics = best_q_data.get("metrics", {})
        q_res = best_q_data.get("quantum_metrics", best_q_metrics.get("quantum_resources", {}))

        n_qubits      = _safe_int(q_res.get("qubits", q_res.get("n_qubits")), 8)
        n_layers      = _safe_int(q_res.get("n_layers"), 2)
        n_params      = _safe_int(q_res.get("n_params"), 0)
        circuit_depth = _safe_int(q_res.get("circuit_depth"), 0)
        n_executions  = _safe_int(q_res.get("total_circuit_executions", q_res.get("n_circuit_executions")), 0)
        shots         = q_res.get("shots")           # may be None (exact simulation)
        q_train_t     = _safe_float(
            best_q_data.get("resource_usage", {}).get("training_time_seconds",
            best_q_data.get("training_time")), 0.0
        )
        q_infer_t     = _safe_float(
            best_q_data.get("resource_usage", {}).get("inference_time_seconds",
            best_q_data.get("inference_time")), 0.0
        )

        # Derived quantum metrics not stored directly
        cnot_per_layer = (n_qubits * (n_qubits - 1)) // 2
        gate_count_est = (
            n_qubits                             # encoding RY
            + n_layers * n_qubits * 2            # RY + RZ per layer
            + n_layers * cnot_per_layer          # CNOTs per layer
        )
        two_qubit_gates_est = n_layers * cnot_per_layer

        # Performance summary for best quantum
        q_perf = {
            "accuracy":    round(_safe_float(best_q_metrics.get("accuracy")), 4),
            "recall":      round(_safe_float(best_q_metrics.get("recall")), 4),
            "specificity": round(_safe_float(best_q_metrics.get("specificity")), 4),
            "roc_auc":     round(_safe_float(best_q_metrics.get("roc_auc")), 4),
        }

        # ── Classical best model ──────────────────────────────────────
        best_classical_name = comparison.get("best_classical") or "random_forest"
        best_cl_data   = models.get(best_classical_name, {})
        best_cl_train  = _safe_float(best_cl_data.get("training_time"), 0.001)
        best_cl_metrics = best_cl_data.get("metrics", {})
        best_cl_auc    = _safe_float(best_cl_metrics.get("roc_auc"))
        best_cl_recall = _safe_float(best_cl_metrics.get("recall"))

        # ── Pipeline timing breakdown ─────────────────────────────────
        total_pipeline = _safe_float(resource_usage.get("elapsed_time"), 0.0)
        # Fall back: sum of all model training times
        if total_pipeline < 1e-6:
            total_pipeline = sum(
                _safe_float(m.get("training_time")) + _safe_float(m.get("inference_time"))
                for m in models.values()
            )

        # Estimate preprocessing time: total minus all model times
        model_total = sum(
            _safe_float(m.get("training_time")) + _safe_float(m.get("inference_time"))
            for m in models.values()
        )
        preprocess_est = max(0.0, total_pipeline - model_total)

        quantum_pct = _pct(q_train_t + q_infer_t, total_pipeline)

        # ── RAM ───────────────────────────────────────────────────────
        peak_memory_mb = _safe_float(resource_usage.get("peak_memory_mb"))
        ram_peak_gb    = round(peak_memory_mb / 1024.0, 3)
        cpu_avg        = round(_safe_float(resource_usage.get("cpu_percent")), 1)

        # ── Classical comparison verdict ──────────────────────────────
        if best_cl_train > 1e-6:
            speedup = round(q_train_t / best_cl_train, 1)
        else:
            speedup = 0.0

        q_auc = q_perf["roc_auc"]
        auc_diff = round(q_auc - best_cl_auc, 4)
        quantum_worse = auc_diff < 0

        if quantum_worse:
            verdict = (
                f"Classical {best_classical_name} achieves {-auc_diff:.3f} higher ROC-AUC "
                f"and trains {speedup:.1f}x faster. "
                f"Classical model preferred for this dataset/configuration."
            )
        elif auc_diff > 0.02:
            verdict = (
                f"{best_q_name} achieves +{auc_diff:.3f} higher ROC-AUC than {best_classical_name}, "
                f"but trains {speedup:.1f}x slower. "
                f"Promising quantum result -- observed on this dataset only."
            )
        else:
            verdict = (
                f"{best_q_name} and {best_classical_name} show comparable ROC-AUC (delta={auc_diff:+.3f}). "
                f"{best_q_name} trains {speedup:.1f}x slower. "
                f"Performance parity -- classical preferred for efficiency."
            )

        # ── Scalability ───────────────────────────────────────────────
        scalability = _scalability_verdict(n_qubits)

        # ── Deployment recommendation ─────────────────────────────────
        deployment = _deployment_verdict(n_qubits, quantum_worse)

        # ── Original feature count ────────────────────────────────────
        original_features = _safe_int(preprocessing.get("original_features"), 0)
        reduced_features  = _safe_int(preprocessing.get("reduced_features"), n_qubits)

        cost_report = {
            "experiment_id":   experiment_id,
            "experiment_type": "QUANTUM_CLASSICAL_HYBRID",
            "model_type":      f"{best_q_name} + Classical Ensemble",
            "dataset_id":      dataset_id,
            "report_timestamp": datetime.now(timezone.utc).isoformat(),

            "performance_summary": q_perf,

            "computational_cost": {
                "training": {
                    "wall_clock_time_seconds":    round(q_train_t, 2),
                    "cpu_utilization_avg_percent": cpu_avg,
                    "ram_peak_gb":                ram_peak_gb,
                    "ram_peak_mb":                round(peak_memory_mb, 1),
                },
                "inference": {
                    "avg_time_ms": round(q_infer_t * 1000, 1),
                },
            },

            "quantum_cost": {
                "qubits":                   n_qubits,
                "n_layers":                 n_layers,
                "n_params":                 n_params,
                "circuit_depth":            circuit_depth,
                "gate_count":               gate_count_est,
                "two_qubit_gates":          two_qubit_gates_est,
                "shots_per_execution":      shots,
                "total_circuit_executions": n_executions,
                "total_shots": (
                    n_executions * shots if shots and n_executions else None
                ),
            },

            "pipeline_cost_breakdown": {
                "preprocessing_seconds":    round(preprocess_est, 2),
                "quantum_training_seconds": round(q_train_t, 2),
                "total_pipeline_seconds":   round(total_pipeline, 2),
                "quantum_percentage":       quantum_pct,
            },

            "comparison_classical_baseline": {
                "classical_model":         best_classical_name,
                "classical_training_secs": round(best_cl_train, 4),
                "quantum_training_secs":   round(q_train_t, 2),
                "speedup_classical":       speedup,
                "classical_roc_auc":       round(best_cl_auc, 4),
                "quantum_roc_auc":         q_auc,
                "verdict":                 verdict,
            },

            "scalability_assessment": scalability,

            "financial_cost_local": {
                "infrastructure":          "LOCAL_LAPTOP",
                "financial_cost_estimate": 0,
                "cost_units": {
                    "cpu_core_hours": round(q_train_t / 3600, 4),
                    "ram_gb_hours":   round(ram_peak_gb * q_train_t / 3600, 4),
                },
                "note": "Local execution — no cloud quantum cost. "
                        "Financial estimate = 0.",
            },

            "resource_feasibility": {
                "current_environment":     "LOCAL_LAPTOP",
                "this_experiment_status":  scalability["this_experiment_status"],
                "bottleneck": (
                    f"Quantum training time ({round(q_train_t, 1)}s) "
                    f"dominated pipeline ({quantum_pct}%)."
                    if quantum_pct > 50 else
                    f"RAM usage peaked at {round(peak_memory_mb, 0):.0f} MB."
                ),
            },

            "deployment_recommendation": deployment,

            "feature_reduction_info": {
                "original_features":  original_features,
                "reduced_features":   reduced_features,
                "method":             "PCA",
                "note": (
                    "Feature reduction is not optional — it makes the quantum "
                    "branch computationally feasible by mapping high-dimensional "
                    "data to the qubit count."
                ),
            },

            "warnings": [
                "These results are specific to the evaluated dataset and "
                "experimental configuration.",
                "Local simulator results may differ from real quantum hardware.",
                "Model scores are uncalibrated and must not be interpreted as "
                "clinical probabilities.",
                "RESEARCH / BENCHMARKING SYSTEM — not a clinical diagnosis.",
            ],
        }

        logger.info(
            f"CostReportGenerator: done. "
            f"quantum_pct={quantum_pct}%, "
            f"financial_cost=0"
        )
        return cost_report

    def save(self, cost_report: dict, experiment_id: str) -> str:
        """Persist cost report as JSON.

        Saves to ``artifacts/reports/{experiment_id}_cost_report.json``.

        Returns
        -------
        str — absolute path to the written file.
        """
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        path = REPORTS_DIR / f"{experiment_id}_cost_report.json"
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(cost_report, fh, indent=2, default=str)
        logger.info(f"Cost report saved: {path}")
        return str(path)


