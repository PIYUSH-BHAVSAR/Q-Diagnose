    @staticmethod
    def _cards(items: List[tuple]) -> str:
        inner = "".join(
            f'<div class="card">'
            f'<div class="lbl">{label}</div>'
            f'<div class="val">{value}</div>'
            f'</div>'
            for label, value in items
        )
        return f'<div class="cards">{inner}</div>'

    def save(self, html: str, experiment_id: str) -> str:
        """Write the HTML report to disk.

        Saves to ``artifacts/reports/{experiment_id}_report.html``.

        Parameters
        ----------
        html : str
            HTML string produced by ``generate()``.
        experiment_id : str
            Used to construct the filename.

        Returns
        -------
        str — absolute path to the written file.
        """
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        path = REPORTS_DIR / f"{experiment_id}_report.html"
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(html)
        logger.info(f"ReportGenerator: report saved -> {path}")
        return str(path)

    def generate_and_save(
        self,
        experiment: dict,
        cost_report: Optional[dict] = None,
        explanations: Optional[dict] = None,
    ) -> str:
        """Convenience: generate then save.

        Returns
        -------
        str — path to the saved file.
        """
        html = self.generate(experiment, cost_report, explanations)
        return self.save(html, experiment.get("id", "UNKNOWN"))
