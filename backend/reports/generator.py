def _safe_float(v: Any, default: float = 0.0) -> float:
    try:
        return float(v) if v is not None else default
    except (TypeError, ValueError):
        return default


def _safe_int(v: Any, default: int = 0) -> int:
    try:
        return int(v) if v is not None else default
    except (TypeError, ValueError):
        return default


def _pct(value: float, total: float) -> float:
    return round(value / total * 100, 1) if total > 0 else 0.0


def _fmt_pct(v: Any) -> str:
    try:
        return f"{float(v):.1%}"
    except (TypeError, ValueError):
        return "N/A"


def _fmt_f(v: Any, decimals: int = 4) -> str:
    try:
        return f"{float(v):.{decimals}f}"
    except (TypeError, ValueError):
        return "N/A"


def _fmt_s(v: Any, decimals: int = 2) -> str:
    try:
        return f"{float(v):.{decimals}f}s"
    except (TypeError, ValueError):
        return "N/A"


def _scalability_verdict(n_qubits: int) -> dict:
    if n_qubits <= 8:
        status = "FEASIBLE"
        note = (
            f"{n_qubits} qubits: feasible on a standard laptop. "
            "Statevector simulation requires O(2^n) memory; 8 qubits ≈ 2KB state vector."
        )
    elif n_qubits <= 12:
        status = "FEASIBLE_HIGH_RESOURCE"
        note = (
            f"{n_qubits} qubits: feasible but requires elevated RAM (6–16 GB). "
            "Not recommended for standard laptops."
        )
    else:
        status = "NOT_RECOMMENDED_LOCAL"
        note = (
            f"{n_qubits} qubits: NOT recommended for local simulation. "
            "Memory requirements grow exponentially (2^n amplitudes)."
        )
    return {
        "current_environment":    "LOCAL_LAPTOP",
        "this_experiment_status": status,
        "recommended_max_qubits": 8,
        "note":                   note,
    }


def _deployment_verdict(n_qubits: int, quantum_worse: bool) -> dict:
    if quantum_worse:
        readiness = "NOT_RECOMMENDED_PRODUCTION"
        reasons = [
            "Classical baseline achieves comparable or higher performance.",
            "Quantum simulation adds significant compute cost.",
            f"{n_qubits}-qubit VQC suitable for research/validation — not production.",
        ]
        alternative = (
            "Deploy the best classical model for production. "
            "Use VQC results for continued research benchmarking."
        )
    else:
        readiness = "RESEARCH_ONLY"
        reasons = [
            "Quantum model shows promising results on this dataset.",
            "Results require validation on larger, independent datasets.",
            "Local simulator output — real quantum hardware evaluation needed.",
        ]
        alternative = (
            "Continue research evaluation before production deployment. "
            "Validate results on independent datasets."
        )
    return {
        "production_readiness": readiness,
        "reasons":              reasons,
        "alternative":          alternative,
    }


