    def _s1_executive_summary(
        self, experiment_id: str, models: dict, comparison: dict
    ) -> str:
        best_cl_info = comparison.get("best_classical") or comparison.get("classical_best") or "N/A"
        best_cl_name = best_cl_info.get("model_name", "N/A") if isinstance(best_cl_info, dict) else str(best_cl_info)

        best_q_info = comparison.get("best_quantum") or comparison.get("quantum_best") or "N/A"
        best_q_name = best_q_info.get("model_name", "N/A") if isinstance(best_q_info, dict) else str(best_q_info)

        best_info = comparison.get("best_overall") or comparison.get("best_model") or best_cl_name
        best_name = best_info.get("model_name", "N/A") if isinstance(best_info, dict) else str(best_info)

        rec = comparison.get("recommendation_text") or comparison.get("recommendation") or "See model comparison section."

        # KPI cards — dynamic
        best_cl_data = models.get(best_cl_name) or (best_cl_info if isinstance(best_cl_info, dict) else {})
        best_cl_metrics = (best_cl_data.get("metrics") if isinstance(best_cl_data, dict) else {}) or {}
        quantum_models = {k: v for k, v in models.items() if str(v.get("model_type", "")).upper() == "QUANTUM"}
